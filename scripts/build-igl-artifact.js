// Builds the igl-artifact skill for Claude chat (igl-artifact/README.md):
//
//   npm run build
//
// Writes dist/igl-artifact/ and dist/igl-artifact.zip, the file people
// upload to Claude, plus dist/specimen.html: every snippet in patterns.md,
// rendered, for checking the patterns by eye.
//
// The IGL palette and logos come from a frontend-boilerplate checkout, so the
// skill follows the boilerplate when the brand changes. It looks beside this
// repo (../frontend-boilerplate); BOILERPLATE=<path> points elsewhere.
// igl-artifact/kit.css adds the rest.

import {execFileSync} from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import {join, resolve} from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const SRC = join(ROOT, 'igl-artifact');
const OUT = join(ROOT, 'dist');
const SKILL_OUT = join(OUT, 'igl-artifact');

const BOILERPLATE = resolve(
  process.env.BOILERPLATE ?? join(ROOT, '../frontend-boilerplate'),
);
if (!existsSync(join(BOILERPLATE, 'src/index.css'))) {
  throw new Error(
    `No frontend-boilerplate at ${BOILERPLATE}. Clone it beside this repo, or set BOILERPLATE=<path>.`,
  );
}
// A file from the boilerplate.
const read = (path) => readFileSync(join(BOILERPLATE, path), 'utf8');

// The body of the first `<selector> { … }` block in css, by brace matching.
function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start === -1) throw new Error(`No "${selector} {" in src/index.css`);
  let depth = 0;
  for (let i = css.indexOf('{', start); i < css.length; i++) {
    if (css[i] === '{') depth++;
    if (css[i] === '}' && --depth === 0) {
      return css.slice(css.indexOf('{', start) + 1, i);
    }
  }
  throw new Error(`Unclosed "${selector}" block in src/index.css`);
}

// `--name: value;` declarations, with comments dropped.
function declarations(body) {
  return [
    ...body
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g),
  ].map(([, name, value]) => [name, value.trim()]);
}

// From the Tailwind theme: the palette (not the colours aliased to shadcn's
// roles) and the two IGL font stacks, renamed since the kit switches
// between them and the editorial ones.
const FONTS = {
  '--font-display': '--font-classic-display',
  '--font-sans': '--font-classic-body',
};
const tokens = declarations(block(read('src/index.css'), '@theme static'))
  .filter(([, value]) => value !== 'initial' && !value.startsWith('var('))
  .flatMap(([name, value]) => {
    if (FONTS[name]) return [[FONTS[name], value]];
    return name.startsWith('--color-') ? [[name, value]] : [];
  });
for (const required of [
  '--color-dark-blue',
  '--color-yellow-80',
  '--font-classic-display',
]) {
  if (!tokens.some(([name]) => name === required)) {
    throw new Error(`src/index.css no longer defines ${required}`);
  }
}

const iglCss = `/* IGL artifact stylesheet. Generated by scripts/build-igl-artifact.js in
   the innovation-growth-lab/skills repo. Don't edit it inside a document:
   add a second <style> block instead. */

/* The IGL palette and fonts (from frontend-boilerplate's src/index.css). */
:root {
${tokens.map(([n, v]) => `  ${n}: ${v};`).join('\n')}
}

${readFileSync(join(SRC, 'kit.css'), 'utf8').trim()}
`;

// The IGL mark as inline SVG: no title or ids, sized by CSS (so the <svg>
// itself loses its width and height; its shapes keep theirs).
const mark = read('src/assets/logos/igl-mark.svg')
  .replace(/<title>[\s\S]*?<\/title>/, '')
  .replace(/\s(id|data-name)="[^"]*"/g, '')
  .replace(/<svg[^>]*>/, (tag) =>
    tag
      .replace(/\s(width|height)="[\d.]+"/g, '')
      .replace(
        '<svg ',
        '<svg class="logo" role="img" aria-label="Innovation Growth Lab" ',
      ),
  )
  .replace(/<\/path>|<\/rect>|<\/polygon>/g, '')
  .replace(/<(path|rect|polygon)([^>]*?)>/g, '<$1$2/>')
  .replace(/<\/?g>/g, '')
  .replace(/\n\s*/g, '');

// The copy inside each page loses comments and indentation; igl.css keeps
// them for reading. A plain squeeze rather than a minifier: one rule a line.
const pageCss = `/* IGL artifact stylesheet (igl.css). Generated: don't edit, add to the next <style> block. */\n${iglCss
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^\s+/gm, '')
  .replace(/([^}])\n/g, '$1 ')
  .replace(/ +/g, ' ')
  .trim()}`;

// Fill a page's slots: the stylesheet and the logo.
const fill = (html) =>
  html
    .replace('/* IGL_CSS */', () => pageCss)
    .replaceAll('<!--igl:mark-->', () => mark);

const template = readFileSync(join(SRC, 'template.html'), 'utf8');

// The specimen: the template's head, then each pattern from patterns.md
// under its name. Heroes and the nav go full width; the rest in a .wrap.
// ?type=classic, ?corners=soft and ?palette=custom try the switches.
function specimen() {
  const patterns = [
    ...readFileSync(join(SRC, 'patterns.md'), 'utf8').matchAll(
      /^### (.+)\n[\s\S]*?```html\n([\s\S]*?)```/gm,
    ),
  ];
  if (patterns.length < 20) {
    throw new Error(`Only ${patterns.length} patterns found in patterns.md`);
  }
  const body = patterns
    .map(([, name, html]) => {
      const label = `<p class="specimen-name">${name}</p>`;
      return /^<(header|nav)/.test(html)
        ? `<div class="wrap">${label}</div>\n${html}`
        : `<div class="wrap">${label}\n${html}</div>`;
    })
    .join('\n');
  const head = template.slice(0, template.indexOf('<body>'));
  return `${head.replace('<title>Document title', '<title>Specimen').replace(
    /<style>\n\/\* This document's[\s\S]*?<\/style>/,
    `<style>
.appbar, .proto { position: static; }
.specimen-name { margin: 56px 0 14px; padding-top: 10px; border-top: 2px solid var(--ink); color: var(--ink); font: 600 13px/1 var(--font-plex); }
.custom { --hero: #0e4a43; --hero-panel: #0b3a35; --hero-line: #2a6b62; --hero-label: #9cc9c0; --hero-em: #f0c766; --hero-rule: #b07d10; --strong: #0e4a43; --strong-soft: #e0eeeb; --link: #0e4a43; --accent: #b07d10; --accent-text: #85600c; --accent-soft: #fdfaf3; }
</style>`,
  )}<body>
${body}
<div class="wrap"><footer class="footer"><p>igl-artifact · specimen</p><p class="ai-note">Made with Claude</p></footer></div>
<script>
const params = new URLSearchParams(location.search);
if (params.get('type')) document.documentElement.dataset.type = params.get('type');
if (params.get('corners')) document.documentElement.dataset.corners = params.get('corners');
if (params.get('palette') === 'custom') document.documentElement.classList.add('custom');
</script>
${template.slice(template.indexOf('<script>'))}`;
}

// The zip gets passed around, so nothing git ignores goes in it: that's
// where internal pages live (igl-artifact/README.md, "Adding an example").
const ignored = execFileSync(
  'git',
  ['ls-files', '--others', '--ignored', '--exclude-standard', SRC],
  {cwd: ROOT, encoding: 'utf8'},
).trim();
if (ignored) {
  throw new Error(
    `Git ignores these, so they can't go in the kit. Move them to private/:\n${ignored}`,
  );
}

rmSync(OUT, {recursive: true, force: true});
mkdirSync(join(SKILL_OUT, 'logos'), {recursive: true});

writeFileSync(join(SKILL_OUT, 'igl.css'), iglCss);
writeFileSync(join(SKILL_OUT, 'template.html'), fill(template));
for (const file of ['SKILL.md', 'patterns.md']) {
  cpSync(join(SRC, file), join(SKILL_OUT, file));
}
// Examples link ../igl.css rather than carry it, but get the logo filled.
cpSync(join(SRC, 'examples'), join(SKILL_OUT, 'examples'), {recursive: true});
for (const file of readdirSync(join(SKILL_OUT, 'examples'))) {
  if (!file.endsWith('.html')) continue;
  const path = join(SKILL_OUT, 'examples', file);
  writeFileSync(path, fill(readFileSync(path, 'utf8')));
}
for (const logo of [
  'igl-mark.svg',
  'igl-logo-horizontal.svg',
  'igl-logo-primary-reversed.svg',
  'igl-logo-secondary-reversed.svg',
]) {
  cpSync(
    join(BOILERPLATE, 'src/assets/logos', logo),
    join(SKILL_OUT, 'logos', logo),
  );
}
writeFileSync(join(OUT, 'specimen.html'), fill(specimen()));

// Claude's skill upload wants a zip with the skill's folder at its top.
execFileSync('zip', ['-rqX', 'igl-artifact.zip', 'igl-artifact'], {cwd: OUT});

console.log(`Built dist/igl-artifact.zip
  ${tokens.length} palette and font tokens from ${join(BOILERPLATE, 'src/index.css')}
  igl.css ${(Buffer.byteLength(iglCss) / 1024).toFixed(1)} KB
  Specimen: dist/specimen.html (?type=classic, ?corners=soft, ?palette=custom)`);
